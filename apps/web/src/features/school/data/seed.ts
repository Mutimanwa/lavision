const baseAverages = [14.5, 11.25, 16, 9.25, 12.75, 15.25, 10.5, 0, 8.75, 14.75, 12, 13.5];
const subjectOffsets = [0, 0.75, -0.5, 1.25, -1, 0.25];

function createGrades(): Grade[] {
  return students.flatMap((student, studentIndex) => {
    if (student.status !== ("Actif" satisfies StudentStatus)) return [];

    return ["math", "fr", "kir", "ang", "sci", "hg"].map((subjectId, subjectIndex) => ({
      id: `${student.id}-${subjectId}-Trimestre 1`,
      studentId: student.id,
      subjectId,
      term: "Trimestre 1" as const,
      value: Math.max(
        3,
        Math.min(
          19.5,
          Math.round(
            (baseAverages[studentIndex] + subjectOffsets[subjectIndex]) * 4,
          ) / 4,
        ),
      ),
      updatedAt: "2026-10-26T16:30:00.000Z",
    }));
  });
}

function createAttendance(): AttendanceRecord[] {
  return students
    .filter((student) => student.status === "Actif")
    .map((student, index) => ({
      id: `2026-10-27-${student.id}`,
      studentId: student.id,
      classId: student.classId,
      date: "2026-10-27",
      status: index === 3 ? "absent" : index === 6 ? "retard" : "present",
    }));
}

